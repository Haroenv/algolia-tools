import { createHash } from 'node:crypto';
import { expect, test } from 'bun:test';
import { DICTIONARIES, CURRENT_DICTIONARY_PARAM } from './dictionary';
import { searchFromValues, valuesFromSearch } from './share';

// Released dictionaries are frozen: shared links depend on them byte for byte.
// To improve the dictionary add a NEW entry (and hash) here, never change one.
const FROZEN_HASHES: Record<string, string> = {
  d: '86b575bb62292eeb7be0c637baba462ec71ffb65ead164e45e2116440c15379e',
};

test('every registered dictionary is frozen', () => {
  expect(Object.keys(DICTIONARIES).sort()).toEqual(
    Object.keys(FROZEN_HASHES).sort()
  );
  for (const [param, dictionary] of Object.entries(DICTIONARIES)) {
    const hash = createHash('sha256').update(dictionary).digest('hex');
    expect(hash, `dictionary "${param}" was modified`).toBe(
      FROZEN_HASHES[param]
    );
  }
});

test('new links use a registered dictionary', () => {
  expect(DICTIONARIES[CURRENT_DICTIONARY_PARAM]).toBeDefined();
});

// A link generated by the first release. If this breaks, links in the wild
// broke too.
test('golden ?d= link still decodes', async () => {
  const golden =
    '?d=i1YCl63qsDBOTEpGn2XDNglmj1nSZeMu6RydnLGnCuBgRi6wrQOarUMtAAnNlsBmLNBnTSBdOuBURGoxSo_OFDydoq4UCwA';
  expect(await valuesFromSearch(golden)).toEqual([
    `curl 'https://abc-dsn.algolia.net/1/indexes/*/queries?x-algolia-api-key=k&x-algolia-application-id=ABC' -H 'Origin: https://example.com' --data-raw '{"requests":[{"indexName":"products","params":"query=shoes&hitsPerPage=5"}]}'`,
  ]);
});

test('round trips with the current dictionary', async () => {
  const values = ['{"a":"é ☃"}', ''];
  expect(await valuesFromSearch(searchFromValues(values))).toEqual(values);
});

test('legacy ?0=&1= links still work', async () => {
  const sp = new URLSearchParams({ 0: 'a b', 1: '{"x":1}' });
  expect(await valuesFromSearch('?' + sp)).toEqual(['a b', '{"x":1}']);
});
